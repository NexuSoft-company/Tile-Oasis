  id: string;
  name: string;
  category: 'CORE' | 'PLAYER' | 'ECONOMY' | 'PROGRESSION' | 'DAILY' | 'EVENTS' | 'SOCIAL' | 'COMPETITIVE' | 'ACCOUNT' | 'SYSTEM';
